using System.CodeDom.Compiler;
using System.Diagnostics;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace FlashOWare.Analyzers.CSharp.Roslyn.Tests.Generators;

[Generator(LanguageNames.CSharp)]
[System.Diagnostics.CodeAnalysis.SuppressMessage("MicrosoftCodeAnalysisCorrectness", "RS1036:Specify analyzer banned API enforcement setting", Justification = "Testing")]
[System.Diagnostics.CodeAnalysis.SuppressMessage("MicrosoftCodeAnalysisCorrectness", "RS1041:Compiler extensions should be implemented in assemblies targeting netstandard2.0", Justification = "Testing")]
[System.Diagnostics.CodeAnalysis.SuppressMessage("MicrosoftCodeAnalysisCorrectness", "RS1038:Compiler extensions should be implemented in assemblies with compiler-provided references", Justification = "Testing")]
internal sealed class InterceptorMethodGenerator : IIncrementalGenerator
{
	private static readonly string s_generatedCodeAttribute = $"""[global::System.CodeDom.Compiler.GeneratedCodeAttribute("{typeof(InterceptorMethodGenerator).Assembly.GetName().Name}", "{typeof(InterceptorMethodGenerator).Assembly.GetName().Version}")]""";
	private static readonly SymbolDisplayFormat? s_format = SymbolDisplayFormat.FullyQualifiedFormat;

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		IncrementalValueProvider<ImmutableArray<MethodModel>> source = context
			.SyntaxProvider.CreateSyntaxProvider(
				static bool (SyntaxNode node, CancellationToken cancellationToken) =>
				{
					return node is ExpressionStatementSyntax
					{
						Expression: InvocationExpressionSyntax
						{
							Expression: MemberAccessExpressionSyntax
							{
								Name: IdentifierNameSyntax { Identifier.ValueText: "WriteLine" },
							},
							ArgumentList.Arguments.Count: > 0,
						},
					};
				},
				static MethodModel? (GeneratorSyntaxContext context, CancellationToken cancellationToken) =>
				{
					var statement = (ExpressionStatementSyntax)context.Node;
					var expression = (InvocationExpressionSyntax)statement.Expression;

					SymbolInfo info = context.SemanticModel.GetSymbolInfo(expression, cancellationToken);

					if (info.Symbol is not IMethodSymbol method)
					{
						return null;
					}

					if (method.Parameters.Length != 1 || method.Parameters[0].Type.SpecialType != SpecialType.System_String)
					{
						return null;
					}

					InterceptableLocation? location = context.SemanticModel.GetInterceptableLocation(expression, cancellationToken);

					if (location is null)
					{
						return null;
					}

					return new MethodModel(
						location,
						method.ContainingType.ToDisplayString(s_format),
						method.DeclaredAccessibility,
						method.IsStatic,
						method.ReturnsVoid,
						method.ReturnType.ToDisplayString(s_format),
						method.Name,
						method.Parameters[0].Name
					);
				})
			.Where(static bool (MethodModel? source) => source is not null)
			.Collect()!;

		context.RegisterSourceOutput(source, static void (SourceProductionContext context, ImmutableArray<MethodModel> models) =>
		{
			using StringWriter writer = new(new StringBuilder(), CultureInfo.InvariantCulture);
			using IndentedTextWriter source = new(writer, "\t");

			source.WriteLine("// <auto-generated/>");
			source.WriteLine("#nullable enable");
			source.WriteLineNoTabs(null);

			source.WriteLine("namespace System.Runtime.CompilerServices");
			source.WriteLine('{');
			source.Indent++;
			source.WriteLine(s_generatedCodeAttribute);
			source.WriteLine("[global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]");
			source.WriteLine("file sealed class InterceptsLocationAttribute : global::System.Attribute");
			source.WriteLine('{');
			source.Indent++;
			source.WriteLine("public InterceptsLocationAttribute(int version, string data)");
			source.WriteLine('{');
			source.WriteLine('}');
			source.Indent--;
			source.WriteLine('}');
			source.Indent--;
			source.WriteLine('}');
			source.WriteLineNoTabs(null);

			source.WriteLine("namespace FlashOWare.Generated");
			source.WriteLine('{');
			source.Indent++;
			source.WriteLine(s_generatedCodeAttribute);
			source.WriteLine("file static class Interceptors");
			source.WriteLine('{');
			source.Indent++;
			for (int index = 0; index < models.Length; index++)
			{
				MethodModel model = models[index];
				string methodName = $"Interceptor{index}";
				string receiver = model.IsStatic ? "" : $"this {model.TypeName} receiver, ";

				source.WriteLine($"{model.Location.GetInterceptsLocationAttributeSyntax()} // {model.Location.GetDisplayLocation()}");
				source.WriteLine($"{SyntaxFacts.GetText(model.Accessibility)} static {model.ReturnType} {methodName}({receiver}string {model.ParameterName})");
				source.WriteLine('{');
				source.Indent++;
				if (model.IsStatic)
				{
					source.WriteLine($$"""{{(model.ReturnsVoid ? "" : "return ")}}{{model.TypeName}}.{{model.Name}}($"Intercepted ({{model.Location.Data}}): {{{model.ParameterName}}}");""");
				}
				else
				{
					source.WriteLine($$"""{{(model.ReturnsVoid ? "" : "return ")}}receiver.{{model.Name}}($"Intercepted ({{model.Location.Data}}): {{{model.ParameterName}}}");""");
				}
				source.Indent--;
				source.WriteLine('}');
			}

			source.Indent--;
			source.WriteLine('}');
			source.Indent--;
			source.WriteLine('}');

			Debug.Assert(source.Indent == 0, $"Expected {nameof(IndentedTextWriter.Indent)} to be zero, but was {source.Indent}.");
			context.AddSource("Interceptors.g.cs", writer.ToString());
		});
	}
}

file sealed record class MethodModel(InterceptableLocation Location, string TypeName, Accessibility Accessibility, bool IsStatic, bool ReturnsVoid, string ReturnType, string Name, string ParameterName);
